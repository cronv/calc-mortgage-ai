/** Подсказки городов (от 3 символов). */
export function suggestCities(q: string): string[] {
  const s = q.trim().toLowerCase();
  if (s.length < 3) return [];
  return CITIES.filter((c) => c.toLowerCase().includes(s)).slice(0, 8);
}

/** Подсказки адресов (от 3 символов): локальная генерация «город + улица». */
export function suggestAddresses(q: string): string[] {
  const s = q.trim().toLowerCase();
  if (s.length < 3) return [];
  const out: string[] = [];
  for (const city of CITIES) {
    for (const st of STREETS) {
      const full = `г. ${city}, ул. ${st}`;
      if (full.toLowerCase().includes(s)) out.push(full);
      if (out.length >= 8) return out;
    }
  }
  return out;
}
